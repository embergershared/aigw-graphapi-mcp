function Get-FixtureSnapshot {
    param([string] $Root)
    $paths = @('infra/modules/bastion', 'infra/modules/catalog.json', 'infra/core/private-dns-zones.json', 'docs/modules.md', 'unrelated.txt')
    $snapshot = foreach ($relative in $paths) {
        Get-ChildItem -LiteralPath (Join-Path $Root $relative) -File -Recurse -Force | Sort-Object FullName | ForEach-Object {
            "$($_.FullName.Substring($Root.Length))=$((Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash)"
        }
    }
    return $snapshot -join "`n"
}

